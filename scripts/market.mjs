// Turns the market data the chart runs on into a compact module for the engine.
//
//   node scripts/market.mjs    data/nifty-daily.csv  ->  src/game/nifty-data.ts
//
// The CSV is NIFTY 50's daily candles (time, open, high, low, close; the volume the
// source had is left out: the user, 2026-10-16). Every price is kept to the index's
// 0.05 tick. Each day is four numbers: its open against the day before's close
// (0 on the first day), then its high, low and close against its open, in ticks,
// three characters of the base64 alphabet each (18 bits, offset by 2^17). About
// 12 bytes a day instead of about 40 as text; src/game/market.ts reads it back.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "data", "nifty-daily.csv");
const out = join(root, "src", "game", "nifty-data.ts");

const TICK = 0.05;
const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const OFFSET = 1 << 17;
const enc = (v) => {
  const u = v + OFFSET;
  if (!Number.isInteger(v) || u < 0 || u >= 1 << 18) throw new Error(`value ${v} out of range`);
  return B64[u >> 12] + B64[(u >> 6) & 63] + B64[u & 63];
};

const [head, ...lines] = readFileSync(src, "utf8").trim().split(/\r?\n/);
const cols = head.split(",");
const at = (name) => {
  const i = cols.indexOf(name);
  if (i < 0) throw new Error(`no ${name} column`);
  return i;
};
const ix = { time: at("time"), open: at("open"), high: at("high"), low: at("low"), close: at("close") };
const ticks = (s) => Math.round(parseFloat(s) / TICK);
const days = lines.map((line) => {
  const f = line.split(",");
  return { time: f[ix.time], o: ticks(f[ix.open]), h: ticks(f[ix.high]), l: ticks(f[ix.low]), c: ticks(f[ix.close]) };
});
for (const d of days) if (!(d.l <= Math.min(d.o, d.c) && d.h >= Math.max(d.o, d.c))) throw new Error(`${d.time}: high or low outside the body`);

let data = "";
days.forEach((d, i) => {
  data += enc(i ? d.o - days[i - 1].c : 0) + enc(d.h - d.o) + enc(d.l - d.o) + enc(d.c - d.o);
});

const text = [
  "// GENERATED by `npm run market:sync` from data/nifty-daily.csv. Never edit.",
  "//",
  `// NIFTY 50, daily, ${days[0].time} to ${days[days.length - 1].time}: ${days.length} days of open, high, low`,
  "// and close (no volume), encoded by scripts/market.mjs and read by src/game/market.ts.",
  "",
  "export const NIFTY = {",
  '  name: "NIFTY 50",',
  `  first: "${days[0].time}",`,
  `  last: "${days[days.length - 1].time}",`,
  `  days: ${days.length},`,
  `  tick: ${TICK},`,
  `  /** the first day's open, in ticks */`,
  `  open: ${days[0].o},`,
  `  data: "${data}",`,
  "} as const;",
  "",
].join("\n");
writeFileSync(out, text);
console.log(`Wrote src/game/nifty-data.ts: ${days.length} days, ${days[0].time} to ${days[days.length - 1].time}, ${(Buffer.byteLength(text) / 1024).toFixed(1)} KB.`);
